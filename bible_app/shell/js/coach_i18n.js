  function locale() {
    if (global.B100LocalePick && global.B100LocalePick.getLocale) {
      return global.B100LocalePick.getLocale();
    }
    var q = new URLSearchParams(location.search);
    return q.get('locale') || 'zh-Hant';
  }

  function t(key, vars) {
    var pack = STRINGS[locale()] || STRINGS['zh-Hant'];
    var s = pack[key] || STRINGS['zh-Hant'][key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        s = s.replace('{' + k + '}', vars[k]);
      });
    }
    return s;
  }

  function pickField(row, base) {
    if (!row) return '';
    var loc = locale();
    var map = { 'zh-Hant': 'Zh', en: 'En', vi: 'Vi', id: 'Id' };
    var suf = map[loc] || 'Zh';
    return row[base + suf] || row[base + 'Zh'] || row[base + 'En'] || '';
  }

  global.B100CoachI18n = { STRINGS: STRINGS, t: t, locale: locale, pickField: pickField };
